    #[test]
    /// Checks representative circular, reversible, and reversible-circular
    /// traversal orders and confirms each full traversal restores the slice.
    fn circular_and_reversible_traversal_order_and_restoration() {
        let mut values = [1, 2, 3];
        let mut circular = Vec::new();
        let _returned_callback = for_each_circular_permutation(&mut values, 3, |selected| {
            circular.push(selected.to_vec());
            false
        });
        assert_eq!(circular, vec![vec![1, 2, 3], vec![1, 3, 2]]);
        assert_eq!(values, [1, 2, 3]);

        let mut reversible = Vec::new();
        let _returned_callback = for_each_reversible_permutation(&mut values, 3, |selected| {
            reversible.push(selected.to_vec());
            false
        });
        assert_eq!(
            reversible,
            vec![vec![1, 2, 3], vec![1, 3, 2], vec![2, 1, 3]]
        );
        assert_eq!(values, [1, 2, 3]);

        let mut reversible_circular = Vec::new();
        let _returned_callback =
            for_each_reversible_circular_permutation(&mut values, 3, |selected| {
                reversible_circular.push(selected.to_vec());
                false
            });
        assert_eq!(reversible_circular, vec![vec![1, 2, 3]]);
        assert_eq!(values, [1, 2, 3]);
    }

    #[test]
    /// Compares all five traversal families with their count helpers for small
    /// slices, also checking restoration after each complete traversal.
    fn traversal_counts_match_count_helpers_and_restore() {
        for size in 0..=6 {
            for selected in 0..=size {
                let mut values: Vec<_> = (0..size).collect();
                let original = values.clone();
                let mut count = 0u128;
                let _callback = for_each_combination(&mut values, selected, |_| {
                    count += 1;
                    false
                });
                assert_eq!(
                    count,
                    count_each_combination(selected as u128, (size - selected) as u128).unwrap()
                );
                assert_eq!(values, original);

                let mut count = 0u128;
                let _callback = for_each_permutation(&mut values, selected, |_| {
                    count += 1;
                    false
                });
                assert_eq!(
                    count,
                    count_each_permutation(selected as u128, (size - selected) as u128).unwrap()
                );
                assert_eq!(values, original);

                let mut count = 0u128;
                let _callback = for_each_circular_permutation(&mut values, selected, |_| {
                    count += 1;
                    false
                });
                assert_eq!(
                    count,
                    count_each_circular_permutation(selected as u128, (size - selected) as u128)
                        .unwrap()
                );
                assert_eq!(values, original);

                let mut count = 0u128;
                let _callback = for_each_reversible_permutation(&mut values, selected, |_| {
                    count += 1;
                    false
                });
                assert_eq!(
                    count,
                    count_each_reversible_permutation(selected as u128, (size - selected) as u128)
                        .unwrap(),
                    "reversible size={size}, selected={selected}"
                );
                assert_eq!(values, original);

                let mut count = 0u128;
                let _callback =
                    for_each_reversible_circular_permutation(&mut values, selected, |_| {
                        count += 1;
                        false
                    });
                assert_eq!(
                    count,
                    count_each_reversible_circular_permutation(
                        selected as u128,
                        (size - selected) as u128
                    )
                    .unwrap()
                );
                assert_eq!(values, original);
            }
        }
    }

