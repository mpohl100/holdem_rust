//! Combinations and permutations translated from Howard Hinnant's C++ header.
//!
//! The C++ header accepts bidirectional iterators. Safe Rust has no general
//! mutable bidirectional-iterator interface, so this module uses mutable
//! slices and index ranges instead. Element types and callbacks remain generic.
//! Each traversal callback receives the currently selected prefix and returns
//! `true` to stop immediately. As in the source, early exit leaves the current
//! permutation in place; completing a traversal restores the input order.
//!
//! # C++ to Rust mapping
//!
//! C++ `detail` helpers and types are preserved in [`detail`] with their names
//! converted to Rust `snake_case` where applicable. Iterator ranges map to
//! `(first, mid, last)` indices over one slice. C++ count functions throw on
//! overflow; their Rust counterparts return [`CountOverflow`] in `Result`.
//!
//! The explicit function mappings are: `for_each_combination`,
//! `for_each_permutation`, `for_each_circular_permutation`,
//! `for_each_reversible_permutation`,
//! `for_each_reversible_circular_permutation`, `gcd`,
//! `count_each_combination`, `count_each_permutation`,
//! `count_each_circular_permutation`, `count_each_reversible_permutation`, and
//! `count_each_reversible_circular_permutation` retain their names.
//! `call_combine_discontinuous`, `combine_discontinuous3_`, `permute_`,
//! `bound_range`, `call_permute`, `circular_permutation`,
//! `reversible_permutation`, `rev1`, `rev2`, `rev3`, and
//! `reverse_circular_permutation` map to same-spelled `snake_case` items in
//! [`detail`]. In particular, type names use Rust `UpperCamelCase` (for example
//! C++ `rev2` maps to [`detail::Rev2`]).
//! The helper functions `rotate_discontinuous`, `rotate_discontinuous3`,
//! `combine_discontinuous`, `combine_discontinuous3`, and `permute` retain
//! their names. C++ trailing-underscore members map to Rust names without that
//! suffix (for example `first1_` to `first1`); iterator boundary members remain
//! separate boundary fields rather than being combined into a range.
//!
//! The C++ templates accept arbitrary unsigned count types and arbitrary
//! bidirectional iterators. This safe translation uses `u128` counts and
//! contiguous mutable slices. Callback parameters are selected mutable slices
//! rather than iterator pairs; there is no safe equivalent to a general C++
//! mutable bidirectional iterator in the standard library. The low-level
//! `Rev2`/`Rev3` adapters likewise cannot present multiple discontinuous
//! mutable ranges as one callback slice; their Rust adapter methods apply the
//! callback to the innermost range. The C++ reversible-circular adapter is
//! undefined for a zero-length range because it advances the initial iterator;
//! this translation safely treats a zero-size selection as one callback.
//! These are the exact genericity and undefined-input gaps.

/// Error returned when a combinatorial count cannot fit in `u128`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CountOverflow;

impl std::fmt::Display for CountOverflow {
    /// Formats the count-overflow error.
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("combinatorial count overflow")
    }
}

impl std::error::Error for CountOverflow {}

/// Computes the greatest common divisor of `x` and `y`.
#[must_use]
pub fn gcd(mut x: u128, mut y: u128) -> u128 {
    while y != 0 {
        let t = x % y;
        x = y;
        y = t;
    }
    x
}

/// Counts combinations of `d1` selected items and `d2` unselected items.
///
/// # Errors
///
/// Returns [`CountOverflow`] if the exact count cannot fit in `u128`.
pub fn count_each_combination(mut d1: u128, mut d2: u128) -> Result<u128, CountOverflow> {
    if d2 < d1 {
        std::mem::swap(&mut d1, &mut d2);
    }
    if d1 == 0 {
        return Ok(1);
    }
    let mut n = d1.checked_add(d2).ok_or(CountOverflow)?;
    let mut result = n;
    n -= 1;
    let mut k = 2;
    while k <= d1 {
        let divisor = gcd(result, k);
        result /= divisor;
        let factor = n / (k / divisor);
        result = result.checked_mul(factor).ok_or(CountOverflow)?;
        k += 1;
        n -= 1;
    }
    Ok(result)
}

/// Counts permutations of `d1` selected items chosen from `d1 + d2` items.
///
/// # Errors
///
/// Returns [`CountOverflow`] if the exact count cannot fit in `u128`.
pub fn count_each_permutation(d1: u128, d2: u128) -> Result<u128, CountOverflow> {
    let mut n = d1.checked_add(d2).ok_or(CountOverflow)?;
    let mut result = 1u128;
    while n > d2 {
        result = result.checked_mul(n).ok_or(CountOverflow)?;
        n -= 1;
    }
    Ok(result)
}

/// Counts circular permutations, identifying rotations as equivalent.
///
/// # Errors
///
/// Returns [`CountOverflow`] if the exact count cannot fit in `u128`.
pub fn count_each_circular_permutation(d1: u128, d2: u128) -> Result<u128, CountOverflow> {
    if d1 == 0 {
        return Ok(1);
    }
    let mut result;
    if d1 <= d2 {
        result = count_each_combination(d1, d2)?;
        let mut factor = d1 - 1;
        while factor > 1 {
            result = result.checked_mul(factor).ok_or(CountOverflow)?;
            factor -= 1;
        }
    } else {
        let mut n = d1.checked_add(d2).ok_or(CountOverflow)?;
        result = 1;
        while n > d1 {
            result = result.checked_mul(n).ok_or(CountOverflow)?;
            n -= 1;
        }
        n -= 1;
        while n > d2 {
            result = result.checked_mul(n).ok_or(CountOverflow)?;
            n -= 1;
        }
    }
    Ok(result)
}

/// Counts permutations that identify a permutation with its reversal.
///
/// # Errors
///
/// Returns [`CountOverflow`] if the exact count cannot fit in `u128`.
pub fn count_each_reversible_permutation(d1: u128, d2: u128) -> Result<u128, CountOverflow> {
    let mut n = d1.checked_add(d2).ok_or(CountOverflow)?;
    let mut result = 1u128;
    if d1 > 1 {
        result = n;
        if n & 1 == 0 {
            result /= 2;
        }
        n -= 1;
        let mut factor = n;
        if factor & 1 == 0 {
            factor /= 2;
        }
        result = result.checked_mul(factor).ok_or(CountOverflow)?;
        n -= 1;
    }
    while n > d2 {
        result = result.checked_mul(n).ok_or(CountOverflow)?;
        n -= 1;
    }
    Ok(result)
}

/// Counts reversible circular permutations, identifying rotations and reversal.
///
/// # Errors
///
/// Returns [`CountOverflow`] if the exact count cannot fit in `u128`.
pub fn count_each_reversible_circular_permutation(
    d1: u128,
    d2: u128,
) -> Result<u128, CountOverflow> {
    let mut result = count_each_combination(d1, d2)?;
    if d1 > 3 {
        let mut factor = d1 - 1;
        while factor > 2 {
            result = result.checked_mul(factor).ok_or(CountOverflow)?;
            factor -= 1;
        }
    }
    Ok(result)
}

/// Counts combinations in the slice ranges `[first, mid)` and `[mid, last)`.
///
/// # Errors
///
/// Returns [`CountOverflow`] if the exact count cannot fit in `u128`.
///
/// # Panics
///
/// Panics if the boundaries do not satisfy `first <= mid <= last`.
pub fn count_each_combination_for_range(
    first: usize,
    mid: usize,
    last: usize,
) -> Result<u128, CountOverflow> {
    assert!(first <= mid && mid <= last, "invalid combinatoric range");
    count_each_combination((mid - first) as u128, (last - mid) as u128)
}

